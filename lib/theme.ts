export type ThemePresetId = keyof typeof THEME_PRESETS;

export const THEME_GROUPS: ReadonlyArray<{ label: string; ids: ThemePresetId[] }> = [
  {
    label: 'light themes',
    ids: ['light-2026', 'vs-light', 'light-modern', 'light-plus', 'quiet-light', 'solarized-light'],
  },
  {
    label: 'dark themes',
    ids: ['dark-2026', 'abyss', 'vs-dark', 'dark-modern', 'dark-plus', 'kimbie-dark', 'monokai', 'monokai-dimmed', 'red', 'solarized-dark', 'tomorrow-night-blue'],
  },
];

export const DEFAULT_THEME_PRESET: ThemePresetId = 'dark-2026';

export function getThemePreset(themeId?: string | null): ThemePreset {
  if (themeId && themeId in THEME_PRESETS) {
    return THEME_PRESETS[themeId as ThemePresetId];
  }
  return THEME_PRESETS[DEFAULT_THEME_PRESET];
}

export function resolveColorSchemeForTheme(themeId?: string | null): ThemeScheme {
  return getThemePreset(themeId).scheme;
}

export function applyThemePreset(themeId?: string | null) {
  if (typeof document === 'undefined') return;
  const theme = getThemePreset(themeId);
  const root = document.documentElement;
  root.dataset.theme = theme.id;
  root.dataset.themeScheme = theme.scheme;
  root.style.colorScheme = theme.scheme;
  for (const [cssVar, value] of Object.entries(theme.vars)) {
    root.style.setProperty(cssVar, value);
  }
  document.body.style.backgroundColor = theme.vars['--bg-app'];
  document.body.style.color = theme.vars['--text-main'];
}
